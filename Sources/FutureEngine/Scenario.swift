import Foundation

public struct SlotID: Hashable, Sendable, Codable, Comparable, CustomStringConvertible {
    public let rawValue: Int

    public init(rawValue: Int) { self.rawValue = rawValue }

    public static func < (a: SlotID, b: SlotID) -> Bool { a.rawValue < b.rawValue }
    public var description: String { "slot \(rawValue)" }
}

/// Wires one slot's readable variable to another slot's input (SSP: connection).
public struct Connection: Hashable, Sendable, Codable {
    public var from: SlotID
    public var variable: String
    public var to: SlotID
    public var input: String
    public var resampling: Resampling
    public var timing: Timing

    public init(from: SlotID, variable: String, to: SlotID, input: String,
                resampling: Resampling = .hold, timing: Timing = .sameStep) {
        self.from = from
        self.variable = variable
        self.to = to
        self.input = input
        self.resampling = resampling
        self.timing = timing
    }
}

/// Delivers events of one kind generated by one slot to another.
public struct EventRoute: Hashable, Sendable, Codable {
    public var from: SlotID
    public var kind: String
    public var to: SlotID
    public var timing: Timing

    public init(from: SlotID, kind: String, to: SlotID, timing: Timing = .sameStep) {
        self.from = from
        self.kind = kind
        self.to = to
        self.timing = timing
    }
}

/// One value at one communication point.
public struct Sample: Hashable, Sendable {
    public let time: Date
    public let value: Double
}

/// A set of model slots sharing one start date, with their events and connections.
///
/// The scenario plays the role FMI calls the importer: it decides which slot steps next,
/// passes values and events between slots, and recomputes from checkpoints when something
/// changes. Everything is lazy: slots are only computed as far as a query needs.
///
/// Not thread-safe. The app wraps it in an actor (see docs/DESIGN.md, section 4.8).
public final class Scenario {
    /// Slots shown together in the UI and on hardware. The engine itself has no limit.
    public static let bankSize = 8

    public let start: Date
    public let calendar: Calendar
    public let seed: UInt64
    public let checkpointInterval: Int

    private struct Slot {
        let name: String
        let runner: any AnySlotRunner
        var authored: [Event] = []
        var recurring: [RecurringEvent] = []
        var readings: [Reading] = []
        /// Events this slot generated, in time order.
        var generated: [Event] = []
    }

    private var slots: [Slot] = []
    private var explicitConnections: [Connection] = []
    private var explicitRoutes: [EventRoute] = []
    private var isPrepared = false
    private var stepping: Set<SlotID> = []

    /// All connections, including ones resolved from by-name references. Current after `validate()`.
    public private(set) var connections: [Connection] = []
    /// All event routes, including ones resolved from subscriptions. Current after `validate()`.
    public private(set) var eventRoutes: [EventRoute] = []

    public init(start: Date, calendar: Calendar = .utcGregorian, seed: UInt64 = 0x5EED_F07E, checkpointInterval: Int = 32) {
        self.start = start
        self.calendar = calendar
        self.seed = seed
        self.checkpointInterval = checkpointInterval
    }

    // MARK: Slots

    public var slotCount: Int { slots.count }
    public var slotNames: [String] { slots.map(\.name) }

    public func slotID(named name: String) -> SlotID? {
        slots.firstIndex { $0.name == name }.map(SlotID.init(rawValue:))
    }

    public func name(of slot: SlotID) -> String { slots[slot.rawValue].name }

    public func descriptor(of slot: SlotID) -> ModelDescriptor { slots[slot.rawValue].runner.descriptor }

    @discardableResult
    public func addSlot<M: TimelineModel>(_ name: String, model: M) throws -> SlotID {
        guard Self.isValidName(name) else { throw EngineError.invalidSlotName(name) }
        guard slotID(named: name) == nil else { throw EngineError.duplicateSlotName(name) }
        slots.append(Slot(name: name, runner: try makeRunner(for: model, slotName: name)))
        structureChanged()
        return SlotID(rawValue: slots.count - 1)
    }

    /// Swaps the model in a slot, keeping its events and readings. Everything is recomputed.
    public func replaceModel<M: TimelineModel>(of slot: SlotID, with model: M) throws {
        let old = slots[slot.rawValue]
        slots[slot.rawValue] = Slot(name: old.name, runner: try makeRunner(for: model, slotName: old.name),
                                    authored: old.authored, recurring: old.recurring, readings: old.readings)
        structureChanged()
    }

    /// Connects explicitly, for models whose inputs don't name their source (e.g. plug-ins).
    public func connect(_ connection: Connection) {
        explicitConnections.removeAll { $0.to == connection.to && $0.input == connection.input }
        explicitConnections.append(connection)
        structureChanged()
    }

    public func route(_ route: EventRoute) {
        if !explicitRoutes.contains(route) { explicitRoutes.append(route) }
        structureChanged()
    }

    /// Resolves by-name references and checks the wiring, including for same-step loops.
    public func validate() throws {
        try prepareIfNeeded()
    }

    // MARK: Events and readings

    public func events(in slot: SlotID) -> [Event] { slots[slot.rawValue].authored }

    public func recurringEvents(in slot: SlotID) -> [RecurringEvent] { slots[slot.rawValue].recurring }

    public func add(_ event: Event, to slot: SlotID) {
        slots[slot.rawValue].authored.append(event)
        invalidate(slot, from: event.time)
    }

    /// Adds the event, or replaces the one with the same id.
    public func upsert(_ event: Event, in slot: SlotID) {
        if let index = slots[slot.rawValue].authored.firstIndex(where: { $0.id == event.id }) {
            let old = slots[slot.rawValue].authored[index]
            slots[slot.rawValue].authored[index] = event
            invalidate(slot, from: min(old.time, event.time))
        } else {
            add(event, to: slot)
        }
    }

    @discardableResult
    public func removeEvent(id: UUID, from slot: SlotID) -> Event? {
        guard let index = slots[slot.rawValue].authored.firstIndex(where: { $0.id == id }) else { return nil }
        let event = slots[slot.rawValue].authored.remove(at: index)
        invalidate(slot, from: event.time)
        return event
    }

    public func add(_ rule: RecurringEvent, to slot: SlotID) {
        slots[slot.rawValue].recurring.append(rule)
        invalidate(slot, from: rule.first)
    }

    @discardableResult
    public func removeRecurring(id: UUID, from slot: SlotID) -> RecurringEvent? {
        guard let index = slots[slot.rawValue].recurring.firstIndex(where: { $0.id == id }) else { return nil }
        let rule = slots[slot.rawValue].recurring.remove(at: index)
        invalidate(slot, from: rule.first)
        return rule
    }

    public func add(_ reading: Reading, to slot: SlotID) {
        slots[slot.rawValue].readings.append(reading)
        invalidate(slot, from: reading.time)
    }

    /// Events the slot generated up to `date`, computing as needed.
    public func generatedEvents(in slot: SlotID, through date: Date) throws -> [Event] {
        try ensure(slot, through: date)
        return slots[slot.rawValue].generated.filter { $0.time <= date }
    }

    // MARK: Queries

    /// Computes the slot (and everything it depends on) through `date`.
    public func ensure(_ slot: SlotID, through date: Date) throws {
        try prepareIfNeeded()
        try advance(slot, through: date)
    }

    /// The variable's value at the slot's last point at or before `date`.
    public func value(_ variable: String, of slot: SlotID, at date: Date) throws -> Double {
        guard date >= start else { throw EngineError.dateBeforeStart }
        try checkReadable(variable, of: slot)
        try ensure(slot, through: date)
        let runner = slots[slot.rawValue].runner
        let index = runner.lastComputedIndex(atOrBefore: date)!
        return runner.history[index][variable] ?? .nan
    }

    /// The variable at every communication point from `from` through `through`.
    public func series(_ variable: String, of slot: SlotID, from: Date, through: Date) throws -> [Sample] {
        try checkReadable(variable, of: slot)
        try ensure(slot, through: through)
        let runner = slots[slot.rawValue].runner
        guard let high = runner.lastComputedIndex(atOrBefore: through) else { return [] }
        var low = runner.lastComputedIndex(atOrBefore: from) ?? 0
        if runner.times[low] < from { low += 1 }
        guard low <= high else { return [] }
        return (low...high).compactMap { index in
            runner.history[index][variable].map { Sample(time: runner.times[index], value: $0) }
        }
    }

    /// Time of the last point computed so far, or nil if nothing is computed.
    public func computedThrough(_ slot: SlotID) -> Date? {
        slots[slot.rawValue].runner.times.last
    }

    // MARK: Invalidation

    /// Discards the slot's results from `date` on, and those of every slot downstream of it.
    public func invalidate(_ slot: SlotID, from date: Date) {
        var earliest: [SlotID: Date] = [:]
        var pending = [(slot, date)]
        while let (id, from) = pending.popLast() {
            if let seen = earliest[id], seen <= from { continue }
            earliest[id] = from
            if let kept = slots[id.rawValue].runner.truncate(from: from) {
                slots[id.rawValue].generated.removeAll { $0.time > kept }
            } else {
                slots[id.rawValue].generated.removeAll()
            }
            for connection in connections where connection.from == id {
                pending.append((connection.to, from))
            }
            for route in eventRoutes where route.from == id {
                pending.append((route.to, from))
            }
        }
    }

    // MARK: Internals

    static func isValidName(_ name: String) -> Bool {
        guard let first = name.first, first.isLetter else { return false }
        return name.allSatisfy { $0.isLetter || $0.isNumber || $0 == "_" }
    }

    private func makeRunner<M: TimelineModel>(for model: M, slotName: String) throws -> any AnySlotRunner {
        let rate = model.descriptor.stepRate
        guard rate.isValid else { throw EngineError.invalidStepRate(slot: slotName) }
        return SlotRunner(model: model, grid: TimeGrid(start: start, rate: rate, calendar: calendar),
                          checkpointInterval: checkpointInterval)
    }

    private func structureChanged() {
        isPrepared = false
        for index in slots.indices {
            _ = slots[index].runner.truncate(from: start)
            slots[index].generated.removeAll()
        }
    }

    private func checkReadable(_ variable: String, of slot: SlotID) throws {
        let descriptor = slots[slot.rawValue].runner.descriptor
        guard descriptor.readable.contains(where: { $0.name == variable }) else {
            throw EngineError.unknownVariable(slot: slots[slot.rawValue].name, variable: variable)
        }
    }

    /// Seed for a slot, derived from its name so reordering slots doesn't change results.
    private func seed(for slot: SlotID) -> UInt64 {
        var hash: UInt64 = 0xCBF2_9CE4_8422_2325
        for byte in slots[slot.rawValue].name.utf8 {
            hash = (hash ^ UInt64(byte)) &* 0x0000_0100_0000_01B3
        }
        return splitMix(seed ^ hash)
    }

    private func prepareIfNeeded() throws {
        guard !isPrepared else { return }
        var resolvedConnections = explicitConnections
        var resolvedRoutes = explicitRoutes

        for (index, slot) in slots.enumerated() {
            let to = SlotID(rawValue: index)
            let descriptor = slot.runner.descriptor
            for input in descriptor.inputs {
                guard let reference = input.source else { continue }
                if resolvedConnections.contains(where: { $0.to == to && $0.input == input.name }) { continue }
                guard let from = slotID(named: reference.slot) else {
                    throw EngineError.unknownSlot(reference.slot, referencedBy: slot.name)
                }
                resolvedConnections.append(Connection(from: from, variable: reference.variable, to: to,
                                                      input: input.name, resampling: reference.resampling,
                                                      timing: reference.timing))
            }
            for subscription in descriptor.subscriptions {
                guard let from = slotID(named: subscription.slot) else {
                    throw EngineError.unknownSlot(subscription.slot, referencedBy: slot.name)
                }
                let route = EventRoute(from: from, kind: subscription.kind, to: to, timing: subscription.timing)
                if !resolvedRoutes.contains(route) { resolvedRoutes.append(route) }
            }
        }

        for connection in resolvedConnections {
            let fromName = name(of: connection.from), toName = name(of: connection.to)
            guard connection.from != connection.to else { throw EngineError.selfConnection(slot: toName) }
            guard let produced = descriptor(of: connection.from).readable.first(where: { $0.name == connection.variable }) else {
                throw EngineError.unknownVariable(slot: fromName, variable: connection.variable)
            }
            guard let input = descriptor(of: connection.to).inputs.first(where: { $0.name == connection.input }) else {
                throw EngineError.unknownInput(slot: toName, input: connection.input)
            }
            if let fromUnit = produced.unit, let toUnit = input.unit, fromUnit != toUnit {
                throw EngineError.unitMismatch(from: "\(fromName).\(connection.variable) (\(fromUnit))",
                                               to: "\(toName).\(connection.input) (\(toUnit))")
            }
        }
        for route in resolvedRoutes {
            guard route.from != route.to else { throw EngineError.selfConnection(slot: name(of: route.to)) }
            guard descriptor(of: route.from).emits.contains(route.kind) else {
                throw EngineError.unknownEventKind(slot: name(of: route.from), kind: route.kind)
            }
        }

        try checkForSameStepLoops(resolvedConnections, resolvedRoutes)
        connections = resolvedConnections
        eventRoutes = resolvedRoutes
        isPrepared = true
    }

    private func checkForSameStepLoops(_ connections: [Connection], _ routes: [EventRoute]) throws {
        var downstream = [[Int]](repeating: [], count: slots.count)
        for connection in connections where connection.timing == .sameStep {
            downstream[connection.from.rawValue].append(connection.to.rawValue)
        }
        for route in routes where route.timing == .sameStep {
            downstream[route.from.rawValue].append(route.to.rawValue)
        }
        // 0 = not visited, 1 = on the current path, 2 = finished.
        var marks = [UInt8](repeating: 0, count: slots.count)
        var path: [Int] = []
        func visit(_ node: Int) throws {
            marks[node] = 1
            path.append(node)
            for next in downstream[node] {
                if marks[next] == 1 {
                    let loopStart = path.lastIndex(of: next)!
                    throw EngineError.sameStepLoop(path[loopStart...].map { slots[$0].name } + [slots[next].name])
                }
                if marks[next] == 0 { try visit(next) }
            }
            path.removeLast()
            marks[node] = 2
        }
        for node in slots.indices where marks[node] == 0 {
            try visit(node)
        }
    }

    private func advance(_ slot: SlotID, through date: Date) throws {
        guard date >= start else { return }
        let runner = slots[slot.rawValue].runner
        while runner.grid.point(runner.computedCount) <= date {
            try computeNext(slot)
        }
    }

    private func computeNext(_ id: SlotID) throws {
        let slot = slots[id.rawValue]
        guard !stepping.contains(id) else { throw EngineError.reentrantStep(slot: slot.name) }
        stepping.insert(id)
        defer { stepping.remove(id) }

        let runner = slot.runner
        let index = runner.computedCount
        let window = StepWindow.forStep(index, on: runner.grid)

        var inputs: [String: Double] = [:]
        for connection in connections where connection.to == id {
            inputs[connection.input] = try inputValue(connection, index: index, grid: runner.grid)
        }
        for input in runner.descriptor.inputs where inputs[input.name] == nil {
            inputs[input.name] = input.start
        }

        var events: [Event] = []
        var readings: [Reading] = []
        if index > 0 {
            events += slot.authored.filter { window.contains($0.time) }
            for rule in slot.recurring {
                events += rule.occurrences(in: window, calendar: calendar)
            }
            for route in eventRoutes where route.to == id {
                events += try deliveredEvents(route, index: index, grid: runner.grid)
            }
            events.sort(by: Event.stepOrder)
            readings = slot.readings.filter { window.contains($0.time) }
        }

        let slotSeed = seed(for: id)
        let context = StepContext(index: index, window: window, stepRate: runner.descriptor.stepRate,
                                  scenarioStart: start, inputs: inputs, events: events, readings: readings,
                                  seed: slotSeed, calendar: calendar)
        do {
            if index == 0 {
                try runner.computeStart(context)
            } else {
                let generated = try runner.computeStep(context)
                let stamped = generated.enumerated().map { offset, event in
                    Event(id: UUID.deterministic(slotSeed ^ UInt64(index), UInt64(offset)), time: window.upper,
                          kind: event.kind, values: event.values, source: .generated(slot: slot.name))
                }
                slots[id.rawValue].generated.append(contentsOf: stamped)
            }
        } catch let error as EngineError {
            throw error
        } catch {
            throw EngineError.modelFailed(slot: slot.name, message: String(describing: error))
        }
    }

    private func inputValue(_ connection: Connection, index: Int, grid: TimeGrid) throws -> Double {
        let window: StepWindow
        switch connection.timing {
        case .sameStep:
            window = StepWindow.forStep(index, on: grid)
        case .previousStep:
            guard index > 0 else {
                return descriptor(of: connection.to).variable(named: connection.input)?.start ?? 0
            }
            window = StepWindow.forStep(index - 1, on: grid)
        }
        try advance(connection.from, through: window.upper)
        return try sample(connection.from, variable: connection.variable, resampling: connection.resampling, window: window)
    }

    private func sample(_ slot: SlotID, variable: String, resampling: Resampling, window: StepWindow) throws -> Double {
        let runner = slots[slot.rawValue].runner
        func value(at index: Int) throws -> Double {
            guard let value = runner.history[index][variable] else {
                throw EngineError.unknownVariable(slot: name(of: slot), variable: variable)
            }
            return value
        }
        func held() throws -> Double {
            guard let index = runner.lastComputedIndex(atOrBefore: window.upper) else {
                preconditionFailure("producer not computed through \(window.upper)")
            }
            return try value(at: index)
        }

        if resampling == .hold { return try held() }
        let indices = runner.computedIndices(in: window)
        if indices.isEmpty { return resampling == .sum ? 0 : try held() }
        let values = try indices.map(value(at:))
        switch resampling {
        case .hold: return try held()
        case .mean: return values.reduce(0, +) / Double(values.count)
        case .sum: return values.reduce(0, +)
        case .min: return values.min()!
        case .max: return values.max()!
        }
    }

    private func deliveredEvents(_ route: EventRoute, index: Int, grid: TimeGrid) throws -> [Event] {
        let window: StepWindow
        switch route.timing {
        case .sameStep:
            window = StepWindow.forStep(index, on: grid)
        case .previousStep:
            // Step 0 is the start instant, which never has generated events.
            guard index > 1 else { return [] }
            window = StepWindow.forStep(index - 1, on: grid)
        }
        try advance(route.from, through: window.upper)
        return slots[route.from.rawValue].generated.filter { $0.kind == route.kind && window.contains($0.time) }
    }
}
