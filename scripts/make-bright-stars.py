#!/usr/bin/env python3
"""Turns the Yale Bright Star Catalogue into the compact table the sky map draws from.

    python3 -I scripts/make-bright-stars.py heasarc_bsc5p.tdat.gz \
        > Sources/FutureVisuals/BrightStarsData.swift

The catalogue (5th revised edition, Hoffleit and Warren, 1991) comes from NASA's HEASARC:
https://heasarc.gsfc.nasa.gov/FTP/heasarc/dbase/tdat_files/heasarc_bsc5p.tdat.gz, which marks it
public. Nothing downloads it at build or run time: run this again by hand to update the stars.

Each line of the table is one star brighter than magnitude 5.5, brightest first:

    HR|right ascension|declination|magnitude|B−V

HR is the star's Harvard Revised number, right ascension and declination are J2000 degrees, and
B−V is its colour index (blue below 0, white about 0.5, orange above 1), empty when unknown.
"""
import gzip
import sys

FAINTEST = 5.5


def main(path):
    with gzip.open(path, "rt", encoding="latin-1") as handle:
        lines = handle.read().splitlines()
    order = None
    data = False
    stars = []
    for line in lines:
        if line.startswith("line[1] = "):
            order = line[len("line[1] = "):].split()
            continue
        if line.startswith("<DATA>"):
            data = True
            continue
        if line.startswith("<END>"):
            break
        if not data or not line.strip():
            continue
        fields = line.split("|")
        row = dict(zip(order, fields))
        try:
            ra, dec, vmag = float(row["ra"]), float(row["dec"]), float(row["vmag"])
            hr = int(row["hr"])
        except (KeyError, ValueError):
            continue  # a few entries are novae or other objects without a position or magnitude
        if vmag > FAINTEST:
            continue
        bv = row.get("bv_color", "").strip()
        try:
            bv = f"{float(bv):.2f}"
        except ValueError:
            bv = ""
        stars.append((vmag, hr, ra, dec, bv))
    stars.sort()
    if len(set(star[1] for star in stars)) != len(stars):
        raise SystemExit("Two stars have the same HR number")

    print("// Generated by scripts/make-bright-stars.py from the Yale Bright Star Catalogue, 5th revised")
    print(f"// edition, through NASA's HEASARC. {len(stars)} stars brighter than magnitude {FAINTEST}. Don't edit by hand.")
    print()
    print("extension BrightStars {")
    print("    /// One line per star, brightest first: HR|right ascension|declination|magnitude|B−V.")
    print('    static let table = #"""')
    for vmag, hr, ra, dec, bv in stars:
        print(f"{hr}|{ra:.3f}|{dec:.3f}|{vmag:.2f}|{bv}")
    print('"""#')
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
