#!/usr/bin/env python3
"""Turns Natural Earth's 1:110m countries into the compact table the world map draws from.

    python3 -I scripts/make-world-countries.py ne_110m_admin_0_countries.geojson \
        > Sources/FutureVisuals/WorldCountriesData.swift

The GeoJSON comes from https://github.com/nvkelso/natural-earth-vector (geojson/), which is in the
public domain. Nothing downloads it at build or run time: run this again by hand to update the map.

Each line of the table is one country:

    CODE|Name|label longitude|label latitude|population|ring;ring;...

CODE is the ISO 3166 alpha-3 code (ISO_A3_EH), or Natural Earth's own (ADM0_A3) for places
without one, such as Kosovo. A ring is its first point, then the change to each next point, in
hundredths of a degree: "255,4656 -12,3 40,-7". Longitude comes first, as in GeoJSON.
"""
import json
import sys


def ring_text(ring):
    out = []
    last = None
    for lon, lat in ring:
        point = (round(lon * 100), round(lat * 100))
        if last is None:
            out.append(f"{point[0]},{point[1]}")
        else:
            delta = (point[0] - last[0], point[1] - last[1])
            if delta == (0, 0):
                continue
            out.append(f"{delta[0]},{delta[1]}")
        last = point
    return " ".join(out)


def main(path):
    with open(path, encoding="utf-8") as handle:
        data = json.load(handle)
    lines = []
    version = None
    for feature in data["features"]:
        props = feature["properties"]
        version = version or props.get("NE_VERSION") or props.get("ne_version")
        code = props.get("ISO_A3_EH")
        if not code or code == "-99":
            code = props["ADM0_A3"]
        name = props.get("NAME_EN") or props["NAME"]
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        # Outer rings only: holes in countries at this scale are lakes and enclaves too small to see.
        rings = [ring_text(polygon[0]) for polygon in polygons]
        population = int(props.get("POP_EST") or 0)
        for field in (name,):
            if "|" in field or "\n" in field:
                raise SystemExit(f"{code}'s name has a character the table can't hold")
        lines.append(f"{code}|{name}|{props['LABEL_X']:.2f}|{props['LABEL_Y']:.2f}|{population}|{';'.join(rings)}")
    lines.sort()
    codes = [line.split("|")[0] for line in lines]
    if len(codes) != len(set(codes)):
        raise SystemExit("Two countries have the same code")

    print("// Generated by scripts/make-world-countries.py from Natural Earth's 1:110m Admin 0 countries")
    print(f"// (public domain, naturalearthdata.com), version {version or 'unknown'}. Don't edit by hand.")
    print()
    print("extension WorldCountries {")
    print("    /// One line per country: CODE|Name|label longitude|label latitude|population|rings, as the")
    print("    /// script's notes describe.")
    print('    static let table = #"""')
    for line in lines:
        print(line)
    print('"""#')
    print("}")


if __name__ == "__main__":
    main(sys.argv[1])
